const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const js=fs.readFileSync(path.join(__dirname,'../shared/js/data-adapter.js'),'utf8');
const storage=new Map([['safePermitSubmittedPermits',JSON.stringify([{id:'PTW-1038',status:'Pending Admin Approval',basicInfo:{workerName:'Yazan Saleh'}}])]]);
const window={localStorage:{getItem:k=>storage.get(k)??null,setItem:(k,v)=>storage.set(k,v),removeItem:k=>storage.delete(k)},dispatchEvent(){}};
vm.runInNewContext(js,{window,CustomEvent:function(){},console});
(async()=>{
 const repo=window.SafePermitData.repository;
 let p=await repo.getPermit('PTW-1038');
 assert.equal(p.riskAssessment.hazards[0].residualScore,8);
 assert.equal(p.riskAssessment.hazards[0].initialScore,12);
 await repo.savePermit({id:'PTW-1038',status:'Stopped'});
 p=await repo.getPermit('PTW-1038');
 assert.equal(p.riskAssessment.hazards[0].residualScore,8);
 await repo.savePermit({id:'PTW-1038',status:'Pending Admin Approval'});
 p=await repo.getPermit('PTW-1038');
 assert.equal(p.riskAssessment.hazards[0].residualScore,8);
 const userRisk={hazards:[{hazard:'Reviewed',initialScore:15,residualScore:10}]};
 await repo.savePermit({id:'PTW-1038',riskAssessment:userRisk});
 p=await repo.getPermit('PTW-1038');
 assert.equal(p.riskAssessment.hazards[0].residualScore,10);
 assert.equal((await repo.getPermit('UNKNOWN-1')),null);
 const missing=await repo.savePermit({id:'UNKNOWN-1',status:'Draft'});
 assert.equal(missing.riskAssessment,undefined);
 const adminSource=fs.readFileSync(path.join(__dirname,'../admin/review-permit/review-permit.js'),'utf8');
 assert.match(adminSource,/Not Assessed/);
 console.log('v12.6.2 preservation tests passed');
})().catch(e=>{console.error(e);process.exitCode=1});
