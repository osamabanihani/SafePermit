const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../shared/js/data-adapter.js'),'utf8');
const db=new Map([['safePermitSubmittedPermits',JSON.stringify([{id:'PTW-1038',status:'Stopped',previousStatusBeforeStop:'Pending Admin Approval',stopWorkCaseId:'S-1'}])]]);
const localStorage={getItem:k=>db.get(k)??null,setItem:(k,v)=>db.set(k,v),removeItem:k=>db.delete(k)};
const window={localStorage,dispatchEvent(){},CustomEvent:function(){}};
vm.runInNewContext(source,{window,console,CustomEvent:window.CustomEvent});
(async()=>{
 const repo=window.SafePermitData.repository;
 let p=await repo.getPermit('PTW-1038');
 assert.equal(p.basicInfo.workerName,'Yazan Saleh');
 assert.equal(p.basicInfo.area,'Utility Area');
 assert.equal(p.workTitle,'Hot Work - Pipe Repair');
 assert.equal(p.status,'Stopped');
 await repo.savePermit({...p,status:'Pending Admin Approval'});
 p=await repo.getPermit('PTW-1038');
 assert.equal(p.basicInfo.workerName,'Yazan Saleh');
 assert.equal(p.status,'Pending Admin Approval');
 await repo.savePermit({id:'PTW-1038',status:'Stopped'});
 p=await repo.getPermit('PTW-1038');
 assert.equal(p.basicInfo.workerName,'Yazan Saleh');
 assert.equal(p.basicInfo.site,'Plant B');
 assert.equal(p.status,'Stopped');
 const custom={...p,basicInfo:{...p.basicInfo,workerName:'Custom Real Worker',site:'Custom Site'}};
 await repo.savePermit(custom);
 p=await repo.getPermit('PTW-1038');
 assert.equal(p.basicInfo.workerName,'Custom Real Worker');
 assert.equal(p.basicInfo.site,'Custom Site');
 const unknown=await repo.savePermit({id:'PTW-9999',status:'Stopped'});
 assert.equal(unknown.basicInfo,undefined);
 console.log('v12.6.1 data integrity tests passed');
})().catch(e=>{console.error(e);process.exitCode=1});
